#!/usr/bin/env node
// Generates crates/ui-egui/src/trimio_tokens.rs from the Trimio design-contract tokens.json.
//
//   node scripts/trimio-tokens.mjs <path/to/tokens.json>
//
// tokens.json is the single source of truth (Trimio-UI/design-contract/tokens). Never hand-edit the
// generated Rust file; change tokens.json and run this again.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2] ?? process.env.TRIMIO_TOKENS;
if (!src) {
  console.error('usage: node scripts/trimio-tokens.mjs <tokens.json>  (or set TRIMIO_TOKENS)');
  process.exit(2);
}
const tokens = JSON.parse(readFileSync(src, 'utf8'));
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'crates', 'ui-egui', 'src', 'trimio_tokens.rs');

// Effect band colours come from effects/equalizer/design-tokens.md (shared by every Trimio effect);
// tokens.json does not carry them yet. The 7th is for SoundCraft's extra low-pass band.
const BANDS = ['#A855F7', '#3B82F6', '#10B981', '#F59E0B', '#F97316', '#EF4444', '#EC4899'];

const FIELDS = [
  'bg', 'surface', 'surface-raised', 'surface-overlay', 'border', 'border-subtle', 'border-strong',
  'text-primary', 'text-secondary', 'text-muted', 'text-disabled', 'accent', 'accent-hover',
  'accent-muted', 'accent-subtle', 'accent-text', 'success', 'warning', 'error', 'header-bg',
  'workspace-bg', 'inspector-bg',
];

function color(v) {
  let m = /^#([0-9a-f]{6})$/i.exec(v);
  if (m) {
    const n = parseInt(m[1], 16);
    return `Color32::from_rgb(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255})`;
  }
  m = /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)$/i.exec(v);
  if (m) {
    // Premultiplied so the constant stays a const expression.
    const a = Math.round(Math.min(1, Math.max(0, Number(m[4]))) * 255);
    const pm = (c) => Math.round((Number(c) * a) / 255);
    return `Color32::from_rgba_premultiplied(${pm(m[1])}, ${pm(m[2])}, ${pm(m[3])}, ${a})`;
  }
  throw new Error(`unsupported colour: ${v}`);
}

const field = (k) => k.replace(/-/g, '_');
const px = (v) => `${parseFloat(v).toFixed(1)}`;

function palette(name, theme) {
  const t = tokens.color.themed[theme];
  const rows = FIELDS.map((k) => {
    if (!(k in t)) throw new Error(`tokens.json: color.themed.${theme}.${k} missing`);
    return `        ${field(k)}: ${color(t[k])},`;
  });
  return `    pub const ${name}: TrimioPalette = TrimioPalette {\n${rows.join('\n')}\n    };`;
}

const rust = `//! Trimio Slate design tokens, generated by \`scripts/trimio-tokens.mjs\` from the Trimio
//! design-contract \`tokens.json\` (${tokens.meta?.name ?? 'Trimio'} ${tokens.meta?.version ?? ''}). Do not edit by hand.

use egui::Color32;

/// One theme's colours.
#[derive(Clone, Copy, Debug)]
pub struct TrimioPalette {
${FIELDS.map((k) => `    pub ${field(k)}: Color32,`).join('\n')}
}

impl TrimioPalette {
${palette('DARK', 'dark')}

${palette('LIGHT', 'light')}
}

/// Effect band colours, band 1 first.
pub const BANDS: [Color32; ${BANDS.length}] = [${BANDS.map(color).join(', ')}];

/// Spacing scale (points).
pub mod space {
${Object.entries(tokens.space).map(([k, v]) => `    pub const S${k}: f32 = ${px(v)};`).join('\n')}
}

/// Corner radii (points).
pub mod radius {
${Object.entries(tokens.radius).map(([k, v]) => `    pub const ${k.toUpperCase()}: f32 = ${px(v)};`).join('\n')}
}

/// Header height (points).
pub const HEADER_HEIGHT: f32 = ${px(tokens.layout['header-height'])};
`;

writeFileSync(out, rust);
console.log(`wrote ${out}`);
